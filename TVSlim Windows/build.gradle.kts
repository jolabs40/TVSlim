    }
}

tasks.named<Test>("jvmTest") {
    // TraductionsTest opens `src/main/assets/...` by a relative path, so tests run from the core
    // folder as in the Android build. Windows-only tests work in temp folders and do not care.
    workingDir = noyau.asFile
    // For tests that read the Windows project's own files.
    systemProperty("tvslim.projet", layout.projectDirectory.asFile.absolutePath)
    // Opt-in: screenshots on a real TV, -Pmateriel=192.168.2.135
    providers.gradleProperty("materiel").orNull?.let { systemProperty("tvslim.materiel", it) }
    // Opt-in: logo and card sheet, no TV needed, -Pplanche=1
    providers.gradleProperty("planche").orNull?.let { systemProperty("tvslim.planche", it) }
    // Opt-in, with -Pmateriel: installs a real APK, -Papk=path.apk
    providers.gradleProperty("apk").orNull?.let { systemProperty("tvslim.apk", it) }
    // Opt-in, with -Pmateriel: writes files to the real TV, -Pdepot=1
    providers.gradleProperty("depot").orNull?.let { systemProperty("tvslim.depot", it) }
    // Opt-in, with -Pmateriel: downloads and stores scrcpy, -Pscrcpy=1
    providers.gradleProperty("scrcpy").orNull?.let { systemProperty("tvslim.scrcpy", it) }
    // Opt-in, with -Pmateriel: updates the TV app from GitHub, -PapplicationTv=1
    providers.gradleProperty("applicationTv").orNull?.let { systemProperty("tvslim.applicationtv", it) }
    // Opt-in: runs the real update relay, -PrelaisMsi=... -PrelaisExe=...
    providers.gradleProperty("relaisMsi").orNull?.let { systemProperty("tvslim.relais.msi", it) }
    providers.gradleProperty("relaisExe").orNull?.let { systemProperty("tvslim.relais.exe", it) }
    providers.gradleProperty("relaisPid").orNull?.let { systemProperty("tvslim.relais.pid", it) }
    systemProperty("tvslim.captures", layout.buildDirectory.dir("captures").get().asFile.absolutePath)
    useJUnit()
}

