}

tasks.named<Test>("jvmTest") {
    // TraductionsTest opens `src/main/assets/...` by a relative path, so tests run from the core
    // folder as in the Android build. Windows-only tests work in temp folders and do not care.
    workingDir = core.asFile
    // For tests that read the Windows project's own files.
    systemProperty("tvslim.project", layout.projectDirectory.asFile.absolutePath)
    // Opt-in: screenshots on a real TV, -Phardware=192.168.2.135
    providers.gradleProperty("hardware").orNull?.let { systemProperty("tvslim.hardware", it) }
    // Opt-in: logo and card sheet, no TV needed, -Pplanche=1
    providers.gradleProperty("logoSheet").orNull?.let { systemProperty("tvslim.logoSheet", it) }
    // Opt-in, with -Phardware: installs a real APK, -Papk=path.apk
    providers.gradleProperty("apk").orNull?.let { systemProperty("tvslim.apk", it) }
    // Opt-in, with -Phardware: writes files to the real TV, -Pupload=1
    providers.gradleProperty("upload").orNull?.let { systemProperty("tvslim.upload", it) }
    // Opt-in, with -Phardware: downloads and stores scrcpy, -Pscrcpy=1
    providers.gradleProperty("scrcpy").orNull?.let { systemProperty("tvslim.scrcpy", it) }
    // Opt-in, with -Phardware: updates the TV app from GitHub, -PtvApp=1
    providers.gradleProperty("tvApp").orNull?.let { systemProperty("tvslim.tvApp", it) }
    // Opt-in: runs the real update relay, -PrelaisMsi=... -PrelaisExe=...
    providers.gradleProperty("relayMsi").orNull?.let { systemProperty("tvslim.relay.msi", it) }
    providers.gradleProperty("relayExe").orNull?.let { systemProperty("tvslim.relay.exe", it) }
    providers.gradleProperty("relayPid").orNull?.let { systemProperty("tvslim.relay.pid", it) }
    systemProperty("tvslim.captures", layout.buildDirectory.dir("captures").get().asFile.absolutePath)
    useJUnit()
}

compose.resources {
    packageOfResClass = "net.jolabs40.tvslim.windows.resources"
    publicResClass = false
    generateResClass = always
}

/** Android Studio's JBR has no jpackage, so the installer is built with the Adoptium JDK. */
val packagingJdk = javaToolchains.launcherFor {
    languageVersion = JavaLanguageVersion.of(21)
    vendor = JvmVendorSpec.ADOPTIUM
}

compose.desktop {
    application {
        mainClass = "net.jolabs40.tvslim.windows.MainKt"
        javaHome = packagingJdk.get().metadata.installationPath.asFile.absolutePath

        nativeDistributions {
            targetFormats(TargetFormat.Msi)
            packageName = "TV Slim"
            packageVersion = appVersion
            description = "Reversible debloat for Android TV"
            vendor = "jolabs40"
            copyright = "jolabs40"

            // What `suggestRuntimeModules` lists, plus what no dependency analysis sees: Ed25519 and
            // TLS (jdk.crypto.ec), French month names (jdk.localedata), screen readers (jdk.accessibility).
            modules(
                "java.instrument",
                "java.net.http",
                "jdk.unsupported",
                "jdk.crypto.ec",
                "jdk.localedata",
                "jdk.accessibility",
            )

            windows {
                iconFile.set(project.file("packaging/tvslim.ico"))
                // Never change: it makes a new version replace the old one instead of installing
                // alongside it.
                upgradeUuid = "b2c131f4-d4d2-415b-980e-57b089c14718"
                // Per-user install: no admin rights, no UAC prompt, so auto-updates run silently.
                perUserInstall = true
                dirChooser = false
                menu = true
                menuGroup = "TV Slim"
                shortcut = true
            }
        }
    }
}
