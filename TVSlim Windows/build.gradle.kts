import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.compose.multiplatform)
}

// Read from gradle.properties; CI overrides the version with the tag's.
val versionApp: String = providers.gradleProperty("versionApp").get()
val depotGithub: String = providers.gradleProperty("depotGithub").get()
val clePubliqueMisesAJour: String = providers.gradleProperty("clePubliqueMisesAJour").get()
val licenceApp: String = providers.gradleProperty("licenceApp").get()
/** Android APK certificate fingerprint, read from `TVSlim/gradle.properties` so there is no copy to keep in sync. */
val empreinteCertificat: String = providers.fileContents(layout.projectDirectory.file("../TVSlim/gradle.properties"))
    .asText.get().lineSequence().first { it.startsWith("empreinteCertificat=") }.substringAfter('=').trim()
version = versionApp

/**
 * The Android core, compiled from its own sources: catalogue, engine and safeguards exist once, and
 * their tests run in both builds. `CatalogueRepository.kt` reads its files through an Android
 * `Context`, so it is excluded and replaced by `CatalogueRepositoryJvm.kt`, which reads them from the
 * classpath.
 */
val noyau = layout.projectDirectory.dir("../TVSlim/core")

/** Exposes version and repository to the code without depending on the jpackage launcher. */
val genererInfosApp by tasks.registering {
    val dossier = layout.buildDirectory.dir("generated/infosApp/kotlin")
    val version = versionApp
    val depot = depotGithub
    val clePublique = clePubliqueMisesAJour
    val licence = licenceApp
    val empreinte = empreinteCertificat
    inputs.property("version", version)
    inputs.property("depot", depot)
    inputs.property("clePublique", clePublique)
    inputs.property("licence", licence)
    inputs.property("empreinte", empreinte)
    outputs.dir(dossier)
    doLast {
        val fichier = dossier.get().file("net/jolabs40/tvslim/windows/InfosApp.kt").asFile
        fichier.parentFile.mkdirs()
        fichier.writeText(
            """
            |package net.jolabs40.tvslim.windows
            |
            |/** Generated by the `genererInfosApp` Gradle task, do not edit by hand. */
            |internal object InfosApp {
            |    const val VERSION = "$version"
            |    const val DEPOT_GITHUB = "$depot"
            |    const val CLE_PUBLIQUE_MISES_A_JOUR = "$clePublique"
            |    const val LICENCE = "$licence"
            |    /** Expected certificate of the TV app APK downloaded from GitHub. */
            |    const val EMPREINTE_CERTIFICAT_ANDROID = "$empreinte"
            |}
            |""".trimMargin(),
        )
    }
}

kotlin {
    jvmToolchain(21)
