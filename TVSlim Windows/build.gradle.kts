import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.compose.multiplatform)
}

// Read from gradle.properties; CI overrides the version with the tag's.
val appVersion: String = providers.gradleProperty("appVersion").get()
val githubRepository: String = providers.gradleProperty("githubRepository").get()
val updatesPublicKey: String = providers.gradleProperty("updatesPublicKey").get()
val appLicense: String = providers.gradleProperty("appLicense").get()
/** Android APK certificate fingerprint, read from `TVSlim/gradle.properties` so there is no copy to keep in sync. */
val certificateFingerprint: String = providers.fileContents(layout.projectDirectory.file("../TVSlim/gradle.properties"))
    .asText.get().lineSequence().first { it.startsWith("certificateFingerprint=") }.substringAfter('=').trim()
version = appVersion

/**
 * The Android core, compiled from its own sources: catalogue, engine and safeguards exist once, and
 * their tests run in both builds. `CatalogRepository.kt` reads its files through an Android
 * `Context`, so it is excluded and replaced by `CatalogRepositoryJvm.kt`, which reads them from the
 * classpath.
 */
val core = layout.projectDirectory.dir("../TVSlim/core")

/** Exposes version and repository to the code without depending on the jpackage launcher. */
val generateAppInfo by tasks.registering {
    val folder = layout.buildDirectory.dir("generated/infosApp/kotlin")
    val version = appVersion
    val repository = githubRepository
    val publicKeyBase64 = updatesPublicKey
    val license = appLicense
    val fingerprint = certificateFingerprint
    inputs.property("version", version)
    inputs.property("repository", repository)
    inputs.property("clePublique", publicKeyBase64)
    inputs.property("licence", license)
    inputs.property("empreinte", fingerprint)
    outputs.dir(folder)
    doLast {
        val file = folder.get().file("net/jolabs40/tvslim/windows/AppInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package net.jolabs40.tvslim.windows
            |
            |/** Generated by the `generateAppInfo` Gradle task, do not edit by hand. */
            |internal object AppInfo {
            |    const val VERSION = "$version"
            |    const val GITHUB_REPOSITORY = "$repository"
            |    const val UPDATE_PUBLIC_KEY = "$publicKeyBase64"
            |    const val LICENSE = "$license"
            |    /** Expected certificate of the TV app APK downloaded from GitHub. */
            |    const val ANDROID_CERTIFICATE_FINGERPRINT = "$fingerprint"
            |}
            |""".trimMargin(),
        )
    }
}

kotlin {
